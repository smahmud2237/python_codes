'''
While loops will continue to execute a block of code while some condition remains True. For example, while
my pool is not full, keep filling my pool with water. Or, while my dogs are still hungry, keep feeding my dogs.
'''
x = 0
while x < 5:
    print(f"The current value of x is {x}")
    x += 1
else:
    print(f"X = {x}, is not less than 5")
