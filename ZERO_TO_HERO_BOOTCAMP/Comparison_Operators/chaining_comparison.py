'''
1. We can use logical operators to combine comparisons: and, or, not
Let's explore how to use it...
'''
print(('Hello' == 'Hello') and (2 == 2))
print(('Hi' == 'Bye') and (3 == 3))
print((100 == 100) or (2 != 2))
print((100 == 50) or (2 != 3))
print((10 == 100) or (2 == 2))

# Now using not for boolean variable
print(not(1 == 1)) 
# or, 
print(1 != 1)